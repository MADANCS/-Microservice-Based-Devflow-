export interface AuthUser {
  id:        string
  name:      string
  email:     string
  avatar:    string   // initials-based DiceBear URL
  role:      'admin' | 'developer' | 'designer' | 'manager'
  createdAt: string
}

interface AuthState {
  user:        AuthUser | null
  isLoggedIn:  boolean
}

